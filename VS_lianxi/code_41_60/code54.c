/*
# P5736 【深基7.例2】质数筛

## 题目描述

输入 $n$ 个不大于 $10^5$ 的正整数。要求全部储存在数组中，去除掉不是质数的数字，依次输出剩余的质数。

## 输入格式

第一行输入一个正整数 $n$，表示整数个数。

第二行输入 $n$ 个正整数 $a_i$，以空格隔开。

## 输出格式

输出一行，依次输出 $a_i$ 中剩余的质数，以空格隔开。

## 输入输出样例 #1

### 输入 #1

```
5
3 4 5 6 7
```

### 输出 #1

```
3 5 7
```

## 说明/提示

数据保证，$1\le n\le100$，$1 \leq a_i \leq 10^5$。
*/

#include"stdio.h"

int main()
{
    int n, temp;
    int PanDuan(int temp);
    scanf("%d",&n);
    for(int i = 0; i < n ; i++)
    {
        scanf("%d", &temp );
        PanDuan( temp );
    }

    return 0;
}

int PanDuan(int temp)
{
    // 第1个判断：处理小于2的数（1不是质数），直接退出
    if (temp < 2) {
        return; // 非质数，退出函数
    }
    // 第2个判断：处理2（唯一的偶质数），直接打印后退出
    if (temp == 2) {
        printf("%d ", temp);
        return; // 打印完成，退出函数
    }
    // 第3个判断：处理其他偶数（大于2的偶数不是质数），直接退出
    if (temp % 2 == 0) {
        return; // 非质数，退出函数
    }
    // 第4个判断：处理大于2的奇数（遍历奇数因子）
    for (int i = 3; i * i <= temp; i += 2) { // 步长+2，只遍历奇数
        if (temp % i == 0) {
            return; // 能被整除，非质数，退出函数
        }
    }
    // 所有判断通过：是质数，打印后退出
    printf("%d ", temp);
    return 1; // 打印完成，退出函数
}