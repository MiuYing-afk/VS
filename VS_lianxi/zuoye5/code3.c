/*
2. 国民生产总值
【问题描述】

假如我国国民生产总值的年增长率为9%，计算n年后我国国民生产总值与现在相比增长多少百分比。

计算公式为

    p=(1+r)n

r为年增长率，n为年数，p为与现在相比的倍数

要求：n的值需要输入，输出的倍数以百分比的形式输出，保留两位小数（以上公式求的是倍数，需要转换成百分比的格式，例如p的值是2.5678，需要输出256.78%）。

【输入形式】

n
【输出形式】

保留两位小数的百分比值
【样例输入】

10
【样例输出】

236.74%

*/

#include<stdio.h>

int main()
{
    int n;
    float after_zong=1;
    scanf("%d",&n);
    for(int i=1;i<=n;i++)
    {
        after_zong*=1.09;
    }
    printf("%.2f%%",after_zong*100);

    return 0;
}