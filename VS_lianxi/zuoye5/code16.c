/*
15. 数列求和
【问题描述】
计算1+2+3+⋯+(n−1)+n 的值，其中正整数n不大于 100。由于你没有高斯聪明，所以你不被允许使用等差数列求和公式直接求出答案。
【输入】
一个正整数n
1≤n≤100。
【输出】
一个正整数，表示最后求和的答案。
【样例输入】
100
【样例输出】
5050
*/

#include<stdio.h>

int main()
{
    int n,sum=0;
    scanf("%d",&n);
    for(int i=1;i<=n;i++)
    {
        sum+=i;
    }
    printf("%d",sum);
}