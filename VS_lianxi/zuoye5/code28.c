/*
28. 表演打分
【问题描述】

在一次运动会方队表演中，学校安排了十名老师进行打分。对于给定的每个参赛班级的不同打分（百分制整数），
按照去掉一个最高分、去掉一个最低分，再算出平均分的方法，得到该班级的最后得分。

【输入】

一行10个用空格隔开的正整数，表示十名老师的打分。

【输出】

该班级的最终得分，答案保留三位小数。

【样例输入】

90 89 92 90 93 95 88 90 89 88
【样例输出】

90.125
*/

#include<stdio.h>

int main()
{
    int n,max=-1,min=1000,sum=0;
    for(int i=0;i<10;i++)
    {
        scanf("%d",&n);
        if(n>max)max=n;
        if(n<min)min=n;
        sum+=n;
    }
    double average=(sum-min-max)/8.0;
    printf("%.3f",average);

    return 0;
}