#include<stdio.h>
#include<math.h>

int main()
{
    double s,zong=0,start=2;
    int num;
    scanf("%lf",&s);
    for(;(zong>s||fabs(s-zong)<1e-6)!=1;)
    {
        zong+=start;
        start*=0.98;
        num++;
    }
    printf("%d",num);

    return 0;
}