#include "stdio.h"

int main() {
    long long n;
    long long step_count = 1;

    printf("请输入一个正整数：");
    if (scanf("%lld", &n) != 1 || n <= 0) {
        printf("错误：请输入有效的正整数！\n");
        return 1;
    }

    while (n != 1) {
        if (n & 1) {
            // 奇数：3n+1 后必为偶数，直接合并除以2，减少1次循环
            n = (3 * n + 1) >> 1;
            step_count += 2;  // 对应两步操作，步骤数正常累加
        } else {
            // 偶数：批量右移（统计连续的0的个数，一次性右移）
            int shift = 0;
            while ((n & 1) == 0 && n != 1) {
                shift++;
                n >>= 1;
            }
            step_count += shift;
        }
    }

    printf("考拉兹猜想收敛到1的步骤数:%lld\n", step_count);
    return 0;
}
