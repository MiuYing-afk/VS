/*
54. 求第十次反弹高度
【问题描述】

一球从n米高度自由下落，每次落地后返回原高度的一半，再落下。求它在第10次落地时共经过多少米（包括第10次反弹的高度）？
第10次反弹多高？要求 n （n>=100）由键盘输入。

【输入形式】

n

【输出形式】

第10次落地时共经过x米
第10次反弹y米

【样例输入】

100

【样例输出】

第10次落地时共经过299.707031米
第10次反弹0.097656米


*/

#include"stdio.h"

int main()
{
    int n;
    double x=0.0,y;
    scanf("%d",&n);
    y=1.0*n;
    for(int i=0;i<10;i++)
    {
        x+=y;
        y/=2.0;
        x+=y;
    }
    
    printf("第10次落地时共经过%f米\n",x);
    printf("第10次反弹%f米",y);

    return 0;
}