#include <stdio.h>

int main() {
    int N;
    scanf("%d", &N);
    int target = N / 364;  // 由x + 3k = N/364推导而来
    int x, k;
    // 枚举k（从1开始，找最小的k），计算对应的x，找最大的x
    for (k = 1; k <= 100; k++) {
        x = target - 3 * k;
        if (x >= 1 && x <= 100) {
            // 验证总金额是否完全等于N（防止整除误差）
            int weekly = 7 * x + 21 * k;
            if (52 * weekly == N) {
                printf("%d\n%d\n", x, k);
                return 0;
            }
        }
    }
    return 0;
}