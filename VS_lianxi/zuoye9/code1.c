#include<stdio.h>

int main()
{
    int cnt = 0;
    char s[100];  // 题目要求输入长度≤5，100足够
    // 关键修正1：用fgets读取整行（包括空格），避免空格截断
    fgets(s, sizeof(s), stdin);  // 读取一行到s，最多读sizeof(s)-1个字符
    
    // 关键修正2：循环到字符串结束符'\0'，正确判断有效字符
    for (int i = 0; s[i] != '\0'; i++)
    {
        // 有效字符：大小写字母、数字（空格和换行符不计数）
        if ((s[i] >= 'A' && s[i] <= 'Z') || 
            (s[i] >= 'a' && s[i] <= 'z') || 
            (s[i] >= '0' && s[i] <= '9'))
        {
            cnt++;
        }
        // 空格和换行符直接跳过（无需处理）
    }

    printf("%d", cnt);
    return 0;
}