/*
12. 无重复数字的三位数
【问题描述】
有1、2、3、4个数字，能组成多少个互不相同且无重复数字的三位数？都是多少？
【要求】
这些三位数由小到大输出。
【输入】
无
【输出】
按要求输出互不相同且无重复数字的三位数，每行输出8个三位数，用空格分隔
【样例输入】
无
【样例输出】
123 124 132 134 142 143 213 214
231 234 241 243 312 314 321 324 
341 342 412 413 421 423 431 432
*/

#include<stdio.h>

int main()
{
    int i,j,k,cnt=0;
    for(i=1;i<5;i++){
        for(j=1;j<5;j++){
            if(j==i)continue;
            for(k=1;k<5;k++){
                if(k==i||k==j)continue;
                printf("%d ",i*100+j*10+k);
                cnt++;
                if(cnt==8){
                    printf("\n");
                    cnt=0;
                }
            }
        }
    }

    return 0;
}