/*
4. 水仙花数
【问题描述】

打印出所有"水仙花数"，所谓"水仙花数"是指一个三位数，其各位数字立方和等于该本身。例如：153是一个水仙花数，因为153=13+53+33。

【输入】

无
【输出】

所有水仙花数，用空格分隔

【样例输入】

无
【样例输出】

153 370 371 407 
*/

#include<stdio.h>

int main()
{
    int i=100,j,k,l;
    for(;i<1000;i++)
    {
        j=i%10,k=(i/10)%10,l=i/100;
        if(i==j*j*j+k*k*k+l*l*l)
        printf("%d ",i);
    }

    return 0;
}