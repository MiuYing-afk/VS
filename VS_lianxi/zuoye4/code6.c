/*
6. 自由下落的小球
【问题描述】

一球从n米高度自由下落，每次落地后返回原高度的一半，再落下。求它在第10次落地时共经过多少米（包括第10次反弹的高度）？
第10次反弹多高？要求 n （n≥100）由键盘输入。

【输入】

小球对初始高度n（n≥100），n为实数

【输出】

参考样例输出的格式输出结果，小数点后保留6位小数，逗号为英文逗号，没有空格。
【样例输入】

100
【样例输出】

第10次落地时共经过299.707031米,第10次反弹0.097656米
*/

#include<stdio.h>

int main()
{
    double n,sum=0;
    scanf("%lf",&n);
    double fan=n;
    for(int i=0;i<10;i++)
    {
        sum+=fan*2;
        fan/=2.0;
    }
    sum+=fan-n;
    printf("第10次落地时共经过%f米,第10次反弹%f米",sum,fan);

    return 0;
}