/*
20. 搬砖
【问题描述】
请编写程序: 有36 块砖，36 人搬。男人搬4块，女人搬3块，两个小孩抬一砖。要求一次全搬完。问需男人、女人、小孩各若干？（穷举法）。
【输入】
无
【输出】男人数，女人数，小孩数，用英文逗号隔开，没有空格，具体格式见样例输出
注意：输出没有空格，逗号用英文字符
【样例输入】无
【样例输出】
需要3个男人,3个女人,30个小孩
*/

#include<stdio.h>

int main()
{
    int a,b,c;
    for(a=0;a<10;a++){
        for(b=0;b<13;b++){
            for(c=0;c<36;c++){
                if(a*4+b*3+c*0.5==36&&a+b+c==36)
                printf("需要%d个男人,%d个女人,%d个小孩",a,b,c);
            }
        }
    }

    return 0;
}