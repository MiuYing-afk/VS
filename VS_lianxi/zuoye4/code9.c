/*
9. 完全平方数
【问题描述】

一个小于10000的正整数，它加上100后是一个完全平方数，它加上268又是一个完全平方数，请问该数是多少？输出所有这样的数字。

注：若一个数能表示成某个整数的平方的形式，则称这个数为完全平方数，例如4=2*2,9=3*3,25=5*5

【输入】

无
【输出】

小于10000的完全平方数，用空格分隔

【样例输入】

无
【样例输出】

21 261 1581 
*/

#include<stdio.h>
#include<math.h>

int main()
{
    int i=20,b;
    double a;
    for(;i<10000;i++){
        int i1=i+100;
        a=sqrt(i1);
        b=(int)a;
        if(i1==b*b){
            int i2=i+268;
            a=sqrt(i2),b=(int)a;
            if(i2==b*b){
                printf("%d ",i);
            }
        }
    }

    return 0;
}