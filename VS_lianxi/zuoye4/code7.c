/*
7. 猴子吃桃
【问题描述】

猴子吃桃问题。猴子第一天摘下若干个桃子，当即吃了一半，还不过瘾，又多吃了一个。第二天早上又将剩下的桃子吃掉一半，又多吃一个。
以后每天早上都吃了前一天剩下的一半零一个。到第n天早上想再吃时，见只剩下一个桃子了。求第一天共摘多少桃子？  

【输入】

一个整数n（1<n≤15），表示第n天
【输出】

第一天共摘多少桃子，输出格式参考样例输出

【样例输入】

10
【样例输出】

猴子第一天摘了1534个桃子
*/

#include<stdio.h>

int main()
{
    int n,original=1;
    scanf("%d",&n);
    for(;n>1;n--)
    {
        original=(original+1)*2;
    }
    printf("%d",original);

    return 0;
}