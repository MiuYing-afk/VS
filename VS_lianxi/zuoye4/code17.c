/*
17. 输出所有大于100小于等于200的3位偶数，且该偶数的各位数字两两不相同
【问题描述】
输出所有大于100小于等于200的3位偶数，且该偶数的各位数字两两不相同。
【要求】
每行输出10个数，每个数字占6位宽度
【输入】
无
【输出】
参考样例输出
【样例输入】
无
【样例输出】
   102   104   106   108   120   124   126   128   130   132
   134   136   138   140   142   146   148   150   152   154
   156   158   160   162   164   168   170   172   174   176
   178   180   182   184   186   190   192   194   196   198
*/

#include<stdio.h>

int main()
{
    int cnt=0;
    for(int i=0;i<100;i+=2){
        if(i/10!=i%10&&i/10!=1){
            printf("%6d",100+i);
            cnt++;
        }
        if(cnt%10==0)printf("\n");
    }

    return 0;
}