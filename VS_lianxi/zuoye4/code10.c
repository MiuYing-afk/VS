/*
10. 同构数
【问题描述】

编写程序，找出1～99之间的全部同构数。

同构数是这样一组数，它出现在平方数的右边。例如：5是25的右边的数，25是625右边的数，5和25都是同构数。

要求：这些同构数由小到大输出。

【输入】

无
【输出】

1～99之间的全部同构数，用逗号分隔
【样例输入】

无
【样例输出】

1 5 6 25 76 
*/

#include<stdio.h>

int main()
{
    int i=1,n;
    for(;i<100;i++){
        if(i<10){ n=10; }
        else{ n=100; }
        if((i*i)%n==i)
            { printf("%d ",i); }
    }

    return 0;
}