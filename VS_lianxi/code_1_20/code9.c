/*
7. 计算提成
【问题描述】

企业发放的奖金（实数）根据利润（整数）提成。

（1）利润≤10万元时，奖金可提成10% ；

（2）10万元<利润≤20万元时，其中10万元以下部分仍按10%提成，高于10万元（含10万元）的部分，可提成7.5% ；

（3）20万元<利润≤40万元时，其中20万元以下部分仍按上述办法提成，高于20万元的部分按5%提成；

（4）40万元<利润≤60万元时，其中40万元以下部分仍按上述办法提成，高于40万元的部分按3%提成；

（5）60万元<利润≤100万元时，其中60万元以下部分仍按上述办法提成，高于60万的部分按1.5%提成；

（6）100万元<利润时，其中100万元以下部分仍按上述办法提成，超过100万元的部分按1%提成。

【要求】

用switch语句编程序。

【输入】

输入当月利润（整数）

【输出】

应发放奖金提成总数（实数），保留两位小数

【样例输入1】


156890  
【样例输出1】


14266.75
【样例输入2】


450000 
【样例输出2】


29000.00
*/

#include<stdio.h>

int main()
{
    int n,t;
    double zong=0.0;
    scanf("%d",&n);
    t=n/10;
    switch(t)
    {
        default:zong=1+0.75+1+0.6+0.6+0.01*(n-100);break;
        case 10:
        case 9:
        case 8:
        case 7:
        case 6:zong=1+0.75+1+0.6+(n-60)*0.015;break;
        case 5:
        case 4:zong=1+0.75+1+(n-40)*0.03;break;
        case 3:
        case 2:zong=1+0.75+(n-20)*0.05;break;
        case 1:zong=1+(n-10)*0.075;break;
        case 0:zong=n*0.1;
    }

    printf("%.2f",zong);

    return 0;
}