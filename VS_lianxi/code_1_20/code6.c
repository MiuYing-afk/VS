/*
4. 逆序输出数字
【问题描述】

给定一个不多于5位的正整数，按逆序打印出各位数字。例如原数为213，应输出312。

【输入】

一个不多于5位的正整数

【输出】

该数的逆序形式
【样例输入1】

213
【样例输出1】

312
【样例输入2】

12345
【样例输出2】

54321
*/

#include<stdio.h>

int main()
{
    int a,b=0;
    scanf("%d",&a);
    for(a=a;a!=0;a/=10){
        b=b*10+a%10;
    }
    printf("%d",b);

    return 0;
}