/*
6. 求高度
【问题描述】

有4个圆塔，圆心分别为(2，2)、(-2，2)、(2，-2)、(-2，-2)，圆半径为1。

这4个塔的高度都是10米。塔以外无建筑物（即塔外的高度为0）。

输入任一点的坐标，求该点的建筑高度。 
【提示】

在塔内的点高度为10米，不在任何塔内的点高度都为0米

【输入】

某一点的坐标（实数），用空格分隔

【输出】

该点的建筑高度（整数）

【样例输入1】

1.5 1.5
【样例输出1】


10
【样例输入2】


-1 -1
【样例输出2】


0
*/

#include<stdio.h>

int main()
{
    double a,b;
    scanf("%lf%lf",&a,&b);
    if(((2-a)*(2-a)+(2-b)*(2-b)<=1)||
       ((-2-a)*(-2-a)+(2-b)*(2-b)<=1)||
       ((2-a)*(2-a)+(-2-b)*(-2-b)<=1)||
       ((-2-a)*(-2-a)+(-2-b)*(-2-b)<=1))
        {printf("10");}else{
         printf("0");   
        }

    return 0;
}