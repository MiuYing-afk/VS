/*
9. 求三角形的面积
【问题描述】

输入三角形的三边（整数），计算三角形的面积并输出（保留2位小数），如果不能构成三角形，则输出“不是三角形”。

【输入】

三角形的

三边长度（整数），用空格分隔
【输出】三角形对面积（实数，保留2位小数）；如果输入的3边无法构成三角形，则输出“不是三角形”
【样例输入1】

3 5 6
【样例输出2】

7.48
【样例输入2】


1 2 1
【样例输出2】


不是三角形
*/
#include<stdio.h>

int main()
{
    double p,S;
    int a,b,c,max;
    scanf("%d %d %d",&a,&b,&c);

    if(a>=b){max=a;}else{max=b;}
    if(c>=max){max=c;}

    p=(a+b+c)/2.0;
    if((a+b+c-max>max))
    {
    S=sqrt(p*(p-a)*(p-b)*(p-c));
        printf("%.2f",S);
    }else{
        printf("不是三角形");
    }

    return 0;
}