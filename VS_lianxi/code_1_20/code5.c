/*
3. 根据成绩输出等级（用if语句实现）
【问题描述】

给一个百分制成绩，要求输出等级'A'、'B'、'C'、'D'、'E'。

100>=成绩>=90为'A'，90>成绩>=80为'B'，80>成绩>=70为'C'，70>成绩>=60为'D'，60>成绩>=0为'E'。  

成绩不在0~100分之间，要给出“输入有误”的提示。

【输入形式】

一个百分制成绩（实数）
【输出形式】

该成绩对应的等级
【样例输入1】

85
【样例输出1】

B
【样例输出2】

190
【样例输出2】

输入有误
*/

#include<stdio.h>

int main()
{
    int a;
    scanf("%d",&a);

    if(a>100||a<0){
        printf("输入有误");
    }else if(a>=90){
        printf("A");
    }else if(a>=80){
        printf("B");
    }else if(a>=70){
        printf("C");
    }else if(a>=60){
        printf("D");
    }else{
        printf("E");
    }

    return 0;
}