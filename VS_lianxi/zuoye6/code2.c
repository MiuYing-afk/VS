/*
2. 凯撒密码
【问题描述】
人们可以根据明文（一个字符串，只包括小写字母）生成一个凯撒密码（仍然是一个包括小写字母的字符串），
这个密码是将原字符串的每个小写字母改成其在字母表中往后数的第n个，如果数到了最后一个小写字母z，
则从字母表的第一个字母a开始继续数。
比如，当n是1的时候，a会变换成b，z会变换成a；当n是3的时候，a会变换成d，而z会变换成c。
【输入】
第一行是一个整数n，
1≤n≤26；第二行是一串由小写字母构成的明文字符串，小写字母个数不超过50个。
【输出】
依据题意，由明文字符串得到的凯撒密码。
【样例输入】
1
qwez
【样例输出】
rxfa
*/


#include<string.h>
#include<stdio.h>

int main()
{
    int n;
    char str1[51];
    scanf("%d",&n);
    getchar();  //吸收换行符
    fgets(str1,51,stdin);
    str1[strcspn(str1,"\n")]='\0';//去除fgets读取的换行符（可选，若要严格匹配样例输出可做此处理）

    for(int i=0;i<strlen(str1);i++)
    {
        str1[i]=(str1[i]-'a'+n)%26+'a';
    }
    puts(str1);

    return 0;
}