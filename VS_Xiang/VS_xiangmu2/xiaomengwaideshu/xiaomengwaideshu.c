/*
题目描述
某校大门外长度为 l 的马路上有一排树，每两棵相邻的树之间的间隔都是 1 米。我们可以把马路看成一个数轴，马路的一端在数轴 0 的位置，另一端在 l 的位置；数轴上的每
个整数点，即 0,1,2,…,l，都种有一棵树。

由于马路上有一些区域要用来建地铁。这些区域用它们在数轴上的起始点和终止点表示。已知任一区域的起始点和终止点的坐标都是整数，区域之间可能有重合的部分。现在要把
这些区域中的树（包括区域端点处的两棵树）移走。你的任务是计算将这些树都移走后，马路上还有多少棵树。

输入格式
第一行有两个整数，分别表示马路的长度 l 和区域的数目 m。

接下来 m 行，每行两个整数 u,v，表示一个区域的起始点和终止点的坐标。

输出格式
输出一行一个整数，表示将这些树都移走后，马路上剩余的树木数量。

输入输出样例
输入 #1复制

500 3
150 300
100 200
470 471
输出 #1复制

298
说明/提示
【数据范围】

对于 20% 的数据，保证区域之间没有重合的部分。
对于 100% 的数据，保证 1≤l≤10 
4
 ，1≤m≤100，0≤u≤v≤l。
【题目来源】

NOIP 2005 普及组第二题
*/

#include<stdio.h>

int main()
{
    int l,m;
    scanf("%d %d",&l,&m);
    int A[l+1];
    int B[2*m];
    int i,k;
    int cnt=0;
    for (int i=0;i<l+1;i++)
    {
        A[i]=0;
    }
    for(i=0;i<2*m;i+=2){
        int j=i+1;
        scanf("%d %d",&B[i],&B[j]);
    }

    for(i=0;i<2*m;i+=2){
        for(k=B[i];k=B[i+1];k++){
            A[k]=1;
        }
    }

    for(i=0;i<l+1;i++){
        if(A[i]==1){
            cnt++;
        }
    }

    printf("%d",cnt);
    
    return 0;
}