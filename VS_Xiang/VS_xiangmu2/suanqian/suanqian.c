#include <stdio.h>
#include <math.h>

int main() {
    int n;
    scanf("%d", &n);
    
    double sqrt5 = sqrt(5);
    double term1 = pow((1 + sqrt5) / 2, n);
    double term2 = pow((1 - sqrt5) / 2, n);
    double Fn = (term1 - term2) / sqrt5;
    
    printf("%.2lf\n", Fn);
    
    return 0;
}
