/*
题目描述
给定一个整数 N，请将该数各个位上数字反转得到一个新数。
新数也应满足整数的常见形式，即除非给定的原数为零，否则反转后得到的新数的最高位数字不应为零（参见样例 2）。

输入格式
一个整数 N。

输出格式
一个整数，表示反转后的新数。

输入输出样例
输入 #1复制

123
输出 #1复制

321
输入 #2复制

-380
输出 #2复制

-83
说明/提示
【数据范围】

−1,000,000,000≤N≤1,000,000,000。

noip2011 普及组第一题
*/

#include<stdio.h>

int main()
{
    int n,m=0,pan=1;
    scanf("%d",&n);
    if(n<0){
        n=-n;
        pan=-1;
    }
    while(n>0){
        m=m*10+n%10;
        n/=10;
    }
    printf("%d",pan*m);

    return 0;
}