/*
题目描述
请统计某个给定范围 [L,R] 的所有整数中，数字 2 出现的次数。

比如给定范围 [2,22]，数字 2 在数 2 中出现了 1 次，在数 12 中出现 1 次，在数 20 中出现 1 次，
在数 21 中出现 1 次，在数 22 中出现 2 次，所以数字 2 在该范围内一共出现了 6 次。

输入格式
2 个正整数 L 和 R，之间用一个空格隔开。

输出格式
数字 2 出现的次数。

输入输出样例
输入 #1复制

2 22
输出 #1复制

6
输入 #2复制

2 100
输出 #2复制

20
说明/提示
1≤L≤R≤100000。

NOIP2010 普及组 第一题
*/

#include<stdio.h>

int main()
{
    int L,R;
    scanf("%d %d",&L,&R);
    int cnt=0;
    for(int i=L;i<=R;i++){
        int t=i;
        while(t!=0){
            if(t%10==2){
                cnt++;
            }
            t/=10;
        }
    }

    printf("%d",cnt);

    return 0;
}