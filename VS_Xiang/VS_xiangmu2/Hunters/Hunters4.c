/*
题目描述
如果一个十进制数字从左到右读时，所有数位都是从小到大严格递增的，我们就称它是幸运数字。例如：

9、27、1234 都是幸运数字；
11、80、243、1503 不是幸运数字。
对于给定的 a 和 b，请你求出 a,a+1,a+2,⋯,b 中幸运数字的数量。

输入格式
输入一行空格分隔的两个整数 a 和 b。

输出格式
输出一行一个整数，代表 a,a+1,a+2,⋯,b 中幸运数字的数量。

输入输出样例
输入 #1复制

1 100
输出 #1复制

45
输入 #2复制

4096 65536
输出 #2复制

141
说明/提示
对于 100% 的数据，满足 1≤a≤b≤1,000,000。
*/

#include<stdio.h>

int main()
{
    int a,b;
    int A[7];
    for(int i=0;i<7;i++){
        A[i]=0;
    }
    scanf("%d %d",&a,&b);
    int cnt=0;
    for(int i=a;i<=b;i++){
        for(int j=i;j>0;j/=10){
            int k=0;
            A[k]=j%10;
            k++;
        }
        int c=0;
        for(int j=i;j>0;j/10){
            c++;
        }
        for(int j=c;j>=0;j--){
            if(A[j]<A[j-1])cnt++;
        }
    }

    printf("%d",cnt);

    return 0;
}

