/*
题目描述
三个整数分别为 A,B,C。这三个数字不会按照这样的顺序给你，但它们始终满足条件：A<B<C。为了看起来更加简洁明了，我们希望你可以按照给定的顺序重新排列它们。

输入格式
第一行包含三个正整数 A,B,C，不一定是按这个顺序。这三个数字都小于或等于 100。第二行包含三个大写字母 A、B 和 C（它们之间没有空格）表示所需的顺序。

输出格式
在一行中输出 A，B 和 C，用一个 （空格）隔开。

感谢 @smartzzh 提供的翻译

显示翻译
题意翻译
输入输出样例
输入 #1复制

1 5 3
ABC
输出 #1复制

1 3 5
输入 #2复制

6 4 2
CAB
输出 #2复制

6 2 4
*/

#include<stdio.h>

int main()
{
    int A,B,C;
    scanf("%d %d %d",&A,&B,&C);
    char a,b,c;
    scanf("%c%c%c",&a,&b,&c);

    int i;
    if(A>B){i=B;B=A;A=i;}
    if(B>C){i=C;C=B;B=i;}
    if(A>B){i=B;B=A;A=i;}

    printf("%d %d %d",A,B,C);

    return 0;
}