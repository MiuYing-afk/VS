/*
题目描述
用高精度计算出 S=1!+2!+3!+⋯+n!（n≤50）。

其中 ! 表示阶乘，定义为 n!=n×(n−1)×(n−2)×⋯×1。例如，5!=5×4×3×2×1=120。

输入格式
一个正整数 n。

输出格式
一个正整数 S，表示计算结果。

输入输出样例
输入 #1复制

3
输出 #1复制

9
说明/提示
【数据范围】

对于 100% 的数据，1≤n≤50。

【其他说明】

注，《深入浅出基础篇》中使用本题作为例题，但是其数据范围只有 n≤20，使用书中的代码无法通过本题。

如果希望通过本题，请继续学习第八章高精度的知识。

NOIP1998 普及组 第二题
*/

#include<stdio.h>

int main()
{
    int n,S=0;
    int j=1; 
    scanf("%d",&n);
    for(int i=n;i>0;i--){
        int k=1;
        for(j=n;j>0;j--){
            k=k*j;
        }
        S=S+k;
        n--;
    }

    printf("%d",S);

    return 0;
}