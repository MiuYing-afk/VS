/*
题目描述
《庄子》中说到，“一尺之棰，日取其半，万世不竭”。第一天有一根长度为 a 的木棍，从第二天开始，每天都要将这根木棍
锯掉一半（每次除 2，向下取整）。第几天的时候木棍的长度会变为 1？

输入格式
输入一个正整数 a，表示木棍长度。

输出格式
输出一个正整数，表示要第几天的时候木棍长度会变为 1。

输入输出样例
输入 #1复制

100
输出 #1复制

7
说明/提示
数据保证，1≤a≤10 
9
 。
*/

#include<stdio.h>

int main()
{
    int a;
    scanf("%d",&a);
    int cnt=1;

    while(a>1){
        a/=2;
        cnt++;
    }

    printf("%d",cnt);

    return 0;
}