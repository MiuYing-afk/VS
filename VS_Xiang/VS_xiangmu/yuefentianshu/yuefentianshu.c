/*
题目描述
输入年份和月份，输出这一年的这一月有多少天。需要考虑闰年。

输入格式
输入两个正整数，分别表示年份 y 和月数 m，以空格隔开。

输出格式
输出一行一个正整数，表示这个月有多少天。

输入输出样例
输入 #1复制

1926 8
输出 #1复制

31
输入 #2复制

2000 2
输出 #2复制

29
说明/提示
数据保证 1583≤y≤2020，1≤m≤12。
*/

#include<stdio.h>

int main()
{
    int y,m;
    scanf("%d %d",&y,&m);
    int i,j,k;

    if(y%4==0&&y%100!=0){
        i=1;
    }else{
        i=0;
    }
    if(y%100==0&&y%400==0){
        j=1;
    }else{
        j=0;
    }
    if(i==0&&j==0){
       k=0;
    }else{
      k=1;
    }

    if(m==1||m==3||m==5||m==7||m==8||m==10||m==12){
        printf("31");
    }else if(m==4||m==6||m==9||m==11){
        printf("30");
    }else if(m==2){
        if(k==1){
            printf("29");
        }else{
            printf("28");
        }
    }


    return 0;
}

 