/*
题目描述
给出 n，请输出一个直角边长度是 n 的数字直角三角形。所有数字都是 2 位组成的，如果没有 2 位则加上前导 0。

输入格式
输入一个正整数 n。

输出格式
输出如题目要求的数字直角三角形。

输入输出样例
输入 #1复制

5
输出 #1复制

0102030405
06070809
101112
1314
15
说明/提示
数据保证，1≤n≤13。
*/

#include<stdio.h>

int main()
{
    int n;
    scanf("%d",&n);
    int num=1;

    for(int i=0;i<=n;i++){
        for(int j=1;j<=n-i;j++){
            printf("%02d",num);
            num++;
        }
        printf("\n");
    }

    return 0;
}