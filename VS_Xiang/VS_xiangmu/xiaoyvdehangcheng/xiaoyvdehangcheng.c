// 题目描述
// 有一只小鱼，它平日每天游泳 250 公里，周末休息（实行双休日)，假设从周 x 开始算起，过了 n 天以后，小鱼一共累计游泳了多少公里呢？

// 输入格式
// 输入两个正整数 x,n，表示从周 x 算起，经过 n 天。

// 输出格式
// 输出一个整数，表示小鱼累计游泳了多少公里。

// 输入输出样例
// 输入 #1复制

// 3 10
// 输出 #1复制

// 2000
// 说明/提示
// 数据保证，1≤x≤7，1≤n≤10 
// 6
//  。

#include<stdio.h>

int main()
{
    int x,n;
    scanf("%d %d",&x,&n);
    int zong=0;

    while(n>0){
    int i=x%7;
    if(i<6&&i!=0){
        zong+=250;
    }else{
        zong+=0;
    }
    x++;
    n--;
    }

    printf("%d",zong);

    return 0;
}